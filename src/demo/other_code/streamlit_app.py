"""
Streamlit SOC Analyst Console
==============================
Web-based console for Security Operations Center (SOC) analysts.
Provides a human-in-the-loop triage interface for security incident escalations
generated by the Google ADK multi-agent workflow.

Compatible with both legacy escalation files and modern SocTicket schemas.
"""

import os
import time
import json
import re
import streamlit as st
from google.cloud import storage
from google.api_core import exceptions
from streamlit_autorefresh import st_autorefresh

PROJECT_ID = os.getenv("GOOGLE_CLOUD_PROJECT", "oso-ai-503519")
ESCALATION_BUCKET_NAME = os.getenv(
    "ESCALATION_BUCKET",
    f"cymbal-cyber-adk-escalations-bucket_{PROJECT_ID}"
)
ESCALATION_POLL_INTERVAL = 4
NOTIFICATION_DURATION = 5

st.set_page_config(page_title="SOC Analyst Console", page_icon="🛡️", layout="wide")
st.title("🛡️ SOC Analyst Console")
st.caption(f"Project: `{PROJECT_ID}` | Escalation Bucket: `gs://{ESCALATION_BUCKET_NAME}`")

# Session state initialization
if "escalations" not in st.session_state:
    st.session_state.escalations = []
if "selected_ticket_id" not in st.session_state:
    st.session_state.selected_ticket_id = None
if "alert_data" not in st.session_state:
    st.session_state.alert_data = None
if "last_escalation_poll" not in st.session_state:
    st.session_state.last_escalation_poll = 0
if "response_comment" not in st.session_state:
    st.session_state.response_comment = ""
if "decision_choice" not in st.session_state:
    st.session_state.decision_choice = "Genuine Threat"
if "new_alert_timestamp" not in st.session_state:
    st.session_state.new_alert_timestamp = None
if "response_submitted_timestamp" not in st.session_state:
    st.session_state.response_submitted_timestamp = None
if "previous_escalation_ids" not in st.session_state:
    st.session_state.previous_escalation_ids = set()


@st.cache_resource
def get_gcp_clients():
    try:
        return storage.Client(project=PROJECT_ID)
    except Exception as e:
        st.error(f"Failed to initialize GCP Storage client: {e}")
        return None


def fetch_escalations(storage_client, force_refresh=False):
    now = time.time()
    if not force_refresh and (now - st.session_state.get("last_escalation_poll", 0) < ESCALATION_POLL_INTERVAL):
        return

    escalation_list = []
    try:
        bucket = storage_client.bucket(ESCALATION_BUCKET_NAME)
        blobs = bucket.list_blobs()
        current_ids = set()
        for blob in blobs:
            if blob.name.startswith("human_escalation_information_") and blob.name.endswith(".json"):
                try:
                    content = blob.download_as_text()
                    data = json.loads(content)
                    ticket_id = data.get("ticket_id", blob.name)
                    escalation_list.append({
                        "ticket_id": ticket_id,
                        "blob_name": blob.name,
                        "data": data
                    })
                    current_ids.add(ticket_id)
                except Exception as e:
                    pass

        if len(current_ids) > len(st.session_state.previous_escalation_ids):
            st.session_state.new_alert_timestamp = time.time()

        st.session_state.escalations = escalation_list
        st.session_state.previous_escalation_ids = current_ids
        st.session_state.last_escalation_poll = now
    except Exception as e:
        st.session_state.last_escalation_poll = now


def select_ticket(ticket_id, blob_name, data):
    st.session_state.selected_ticket_id = ticket_id
    st.session_state.alert_data = data
    st.session_state.response_comment = ""
    st.session_state.decision_choice = "Genuine Threat"


def submit_analyst_response():
    decision = st.session_state.decision_choice
    comment = st.session_state.response_comment
    data = st.session_state.alert_data

    try:
        storage_client = get_gcp_clients()
        bucket = storage_client.bucket(ESCALATION_BUCKET_NAME)
        ticket_id = data.get("ticket_id") if data else st.session_state.selected_ticket_id
        if not ticket_id:
            st.error("Cannot submit response: Ticket ID is missing.")
            return

        response_filename = f"human_escalation_response_{ticket_id}.json"
        response_blob = bucket.blob(response_filename)
        response_payload = {
            "ticket_id": ticket_id,
            "human_decision": decision,
            "human_comment": comment,
            "timestamp": time.time()
        }
        response_blob.upload_from_string(json.dumps(response_payload, indent=2), content_type="application/json")

        st.session_state.response_submitted_timestamp = time.time()
        st.session_state.selected_ticket_id = None
        st.session_state.alert_data = None
        st.session_state.response_comment = ""
        fetch_escalations(storage_client, force_refresh=True)
    except Exception as e:
        st.error(f"Error submitting response: {e}")


# Autorefresh every 15 seconds
st_autorefresh(interval=15 * 1000, key="data_refresher")

storage_client = get_gcp_clients()
if storage_client:
    fetch_escalations(storage_client)

if st.session_state.get("new_alert_timestamp"):
    if time.time() - st.session_state.new_alert_timestamp < NOTIFICATION_DURATION:
        st.toast("🚨 NEW ESCALATION ALERT RECEIVED!", icon="⚠️")
    else:
        st.session_state.new_alert_timestamp = None

if st.session_state.get("response_submitted_timestamp"):
    if time.time() - st.session_state.response_submitted_timestamp < NOTIFICATION_DURATION:
        st.toast("✅ Resolution submitted to SOC ticketing system.", icon="✅")
    else:
        st.session_state.response_submitted_timestamp = None

# Two-column layout
col1, col2 = st.columns([1, 2], gap="large")

with col1:
    st.subheader(f"Pending Escalations ({len(st.session_state.escalations)})")
    if not st.session_state.escalations:
        st.info("No escalations are currently pending.")
    else:
        for esc in st.session_state.escalations:
            t_id = esc["ticket_id"]
            d = esc["data"]
            user = d.get("user_id", "")
            btn_title = f"{t_id} ({user})" if user else t_id
            st.button(
                btn_title,
                key=t_id,
                use_container_width=True,
                on_click=select_ticket,
                args=(t_id, esc["blob_name"], d)
            )

with col2:
    st.subheader("Alert Investigation & Adjudication")
    if not st.session_state.selected_ticket_id:
        st.info("Select an escalation from the left panel to review forensic evidence.")
    else:
        alert_info = st.session_state.alert_data or {}
        context_text = alert_info.get("context_for_human", "")

        # Transform raw signed URLs into clickable links
        url_pattern = re.compile(r'(https://storage\.googleapis\.com/[^\s\)]+)')
        url_match = url_pattern.search(context_text)
        if url_match:
            found_url = url_match.group(1)
            hyperlink = f"[🔍 Open Desktop Screenshot Evidence]({found_url})"
            context_text = context_text.replace(found_url, hyperlink)

        st.markdown("---")
        st.write(f"**Ticket ID:** `{alert_info.get('ticket_id', st.session_state.selected_ticket_id)}`")
        if alert_info.get("user_id"):
            st.write(f"**Target Entity:** `{alert_info.get('user_id')}` | **Device:** `{alert_info.get('device_id', 'N/A')}`")
        if alert_info.get("threat_score"):
            st.write(f"**Threat Anomaly Score:** `{alert_info.get('threat_score')}`")

        st.warning(f"**Reason for Escalation:** {alert_info.get('agent_reason_for_escalation', 'Suspicious activity detected.')}")

        st.markdown("##### **Multi-Agent Forensic Summary**")
        st.markdown(context_text or "*No forensic context provided.*", unsafe_allow_html=True)

        st.markdown("---")
        st.markdown("#### **SOC Analyst Verdict**")
        st.radio(
            "Investigation Outcome:",
            ("Genuine Threat", "False Positive"),
            key="decision_choice",
            horizontal=True
        )

        st.text_area(
            "Resolution Notes:",
            height=120,
            key="response_comment"
        )

        st.button(
            "Submit Resolution to Ticketing System",
            type="primary",
            on_click=submit_analyst_response
        )
